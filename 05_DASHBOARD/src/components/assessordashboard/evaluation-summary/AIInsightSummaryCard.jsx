export default function AIInsightSummaryCard({
  insights = [],
}) {
  /* ==========================================================
     BACKEND HANDOFF

     Expected data type:

     string[]

     Example:

     [
       "High attention stability during assessment.",
       "Strong procedural decision-making.",
       "Minor hesitation observed during troubleshooting."
     ]

     If no AI insights are available yet, the component safely
     displays "No AI insights available."
     ========================================================== */


  /* ==========================================================
     SAFELY NORMALIZE INSIGHTS

     The database normally provides an array.

     This prevents the UI from breaking if the value is null
     or unexpectedly not an array.
     ========================================================== */

  const safeInsights = Array.isArray(insights)
    ? insights.filter(
        (insight) =>
          insight !== null &&
          insight !== undefined &&
          String(insight).trim() !== ""
      )
    : [];


  return (
    <div
      className="
        w-full
        rounded-xl
        border
        border-gray-200
        bg-white
        p-6
        shadow-sm
      "
    >

      {/* ========================================================
          HEADER
          ======================================================== */}

      <div
        className="
          flex
          items-start
          justify-between
          gap-4
        "
      >

        {/* ------------------------------------------------------
            TITLE + DESCRIPTION
            ------------------------------------------------------ */}

        <div className="min-w-0">

          <h2
            className="
              text-lg
              font-semibold
              text-gray-900
            "
          >
            AI Insight Summary
          </h2>


          <p
            className="
              mt-1
              text-sm
              text-gray-500
            "
          >
            Overview of the trainee's cognitive performance
            generated by the AI evaluation engine.
          </p>

        </div>


        {/* ------------------------------------------------------
            AI INDICATOR
            ------------------------------------------------------ */}

        <div
          className="
            flex
            shrink-0
            items-center
            gap-2
            rounded-full
            bg-blue-50
            px-3
            py-1
          "
        >

          <span
            className="
              h-2
              w-2
              rounded-full
              bg-blue-600
            "
          />

          <span
            className="
              text-xs
              font-medium
              text-blue-700
            "
          >
            AI Generated
          </span>

        </div>

      </div>


      {/* ========================================================
          INSIGHTS

          IMPORTANT:

          There is NO:
              h-full
              flex-1
              overflow-y-auto

          The container therefore grows naturally with the
          bullet content.

          This makes the OUTER WHITE CARD follow the height
          of the bullet section.
          ======================================================== */}

      <div
        className="
          mt-6
          rounded-lg
          border
          border-gray-100
          bg-gray-50
          p-4
        "
      >

        {safeInsights.length > 0 ? (

          <ul
            className="
              space-y-4
            "
          >

            {safeInsights.map(
              (insight, index) => (

                <li
                  key={index}
                  className="
                    flex
                    items-start
                    gap-3
                  "
                >

                  {/* ------------------------------------------------
                      BULLET
                      ------------------------------------------------ */}

                  <div
                    className="
                      mt-1.5
                      h-2
                      w-2
                      shrink-0
                      rounded-full
                      bg-blue-600
                    "
                  />


                  {/* ------------------------------------------------
                      INSIGHT TEXT
                      ------------------------------------------------ */}

                  <p
                    className="
                      min-w-0
                      text-sm
                      leading-relaxed
                      text-gray-700
                    "
                  >
                    {String(insight)}
                  </p>

                </li>

              )
            )}

          </ul>

        ) : (

          <p
            className="
              text-sm
              italic
              text-gray-400
            "
          >
            No AI insights available.
          </p>

        )}

      </div>

    </div>
  );
}