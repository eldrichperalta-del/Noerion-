import { useState } from "react";
import { supabase } from "../../../supabaseClient";

export default function CertificateUploadModal({
  onClose,
  onSave,
}) {
  const [form, setForm] = useState({
    name: "",
    course: "",
    skill: "",
    studentId: "",
    result: "",
  });

  const [saving, setSaving] = useState(false);
  const [error, setError] = useState("");

  const handleChange = (field, value) => {
    setForm((previous) => ({
      ...previous,
      [field]: value,
    }));
  };

  const handleSave = async () => {
    setError("");

    // =========================
    // VALIDATION
    // =========================

    if (!form.name.trim()) {
      setError("Please enter the trainee name.");
      return;
    }

    if (!form.course.trim()) {
      setError("Please enter the qualification/course.");
      return;
    }

    if (!form.skill.trim()) {
      setError("Please enter the skill.");
      return;
    }

    if (!form.studentId.trim()) {
      setError("Please enter the student ID.");
      return;
    }

    if (!form.result.trim()) {
      setError("Please enter the result.");
      return;
    }

    try {
      setSaving(true);

      // =========================
      // GENERATE CERTIFICATE ID
      // =========================

      const year = new Date()
        .getFullYear();

      const randomPart = Math.floor(
        100000 + Math.random() * 900000
      );

      const certificateId =
        `CERT-${year}-${randomPart}`;

      // =========================
      // DATE
      // =========================

      const issuedOn =
        new Date()
          .toISOString()
          .split("T")[0];

      // =========================
      // TRAINEE ID
      // =========================

      const traineeId =
        `TR-${Date.now()}`;

      // =========================
      // INSERT INTO SUPABASE
      // =========================

      const { data, error: insertError } =
        await supabase
          .from("certificates")
          .insert({
            certificate_id: certificateId,

            trainee_id: traineeId,

            trainee_name:
              form.name.trim(),

            student_id:
              form.studentId.trim(),

            qualification:
              form.course.trim(),

            skill:
              form.skill.trim(),

            issued_on:
              issuedOn,

            result:
              form.result.trim(),

            /**
             * These values should eventually
             * be generated by the certificate
             * signing system.
             *
             * Do NOT generate fake signatures
             * in the frontend.
             */
            token: null,
            hash: null,
            signature: null,

            /**
             * Your verification Edge Function
             * expects active certificates to
             * have status = "Valid".
             */
            status: "Valid",
          })
          .select(`
            certificate_id,
            trainee_id,
            trainee_name,
            student_id,
            qualification,
            skill,
            issued_on,
            result,
            token,
            hash,
            signature,
            status,
            created_at
          `)
          .single();

      if (insertError) {
        throw insertError;
      }

      // =========================
      // CONVERT DATABASE RECORD
      // TO UI RECORD
      // =========================

      const newCertificate = {
        certificateId:
          data.certificate_id,

        traineeId:
          data.trainee_id,

        traineeName:
          data.trainee_name,

        studentId:
          data.student_id,

        course:
          data.qualification,

        qualification:
          data.qualification,

        skill:
          data.skill,

        dateIssued:
          data.issued_on,

        issuedOn:
          data.issued_on,

        result:
          data.result,

        token:
          data.token,

        hash:
          data.hash,

        signature:
          data.signature,

        status:
          data.status,

        verificationStatus:
          data.status === "Valid"
            ? "Verified"
            : data.status,

        lastVerificationDate:
          null,

        createdAt:
          data.created_at,

        qrCodeUrl:
          "",
      };

      // =========================
      // RETURN TO PARENT
      // =========================

      if (onSave) {
        onSave(newCertificate);
      }

      // Parent closes the modal.
      // This keeps your existing
      // CertificateManagement flow.
    } catch (err) {
      console.error(
        "Failed to create certificate:",
        err
      );

      setError(
        err?.message ||
          "Failed to create certificate."
      );
    } finally {
      setSaving(false);
    }
  };

  return (
    <div className="modal-backdrop">
      <div className="modal">

        {/* =========================
            TITLE
        ========================= */}

        <h3>
          Upload Certificate
        </h3>

        {/* =========================
            ERROR
        ========================= */}

        {error && (
          <div className="text-red-500">
            {error}
          </div>
        )}

        {/* =========================
            TRAINEE NAME
        ========================= */}

        <input
          placeholder="Trainee Name"
          value={form.name}
          disabled={saving}
          onChange={(e) =>
            handleChange(
              "name",
              e.target.value
            )
          }
        />

        {/* =========================
            STUDENT ID
        ========================= */}

        <input
          placeholder="Student ID"
          value={form.studentId}
          disabled={saving}
          onChange={(e) =>
            handleChange(
              "studentId",
              e.target.value
            )
          }
        />

        {/* =========================
            QUALIFICATION
        ========================= */}

        <input
          placeholder="Qualification / Course"
          value={form.course}
          disabled={saving}
          onChange={(e) =>
            handleChange(
              "course",
              e.target.value
            )
          }
        />

        {/* =========================
            SKILL
        ========================= */}

        <input
          placeholder="Skill"
          value={form.skill}
          disabled={saving}
          onChange={(e) =>
            handleChange(
              "skill",
              e.target.value
            )
          }
        />

        {/* =========================
            RESULT
        ========================= */}

        <input
          placeholder="Result"
          value={form.result}
          disabled={saving}
          onChange={(e) =>
            handleChange(
              "result",
              e.target.value
            )
          }
        />

        {/* =========================
            ACTIONS
        ========================= */}

        <div className="modal-actions">

          <button
            type="button"
            onClick={onClose}
            disabled={saving}
          >
            Cancel
          </button>

          <button
            type="button"
            onClick={handleSave}
            disabled={saving}
          >
            {saving
              ? "Saving..."
              : "Save"}
          </button>

        </div>

      </div>
    </div>
  );
}