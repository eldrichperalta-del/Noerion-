import "@supabase/functions-js/edge-runtime.d.ts";
import { createClient } from "@supabase/supabase-js";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers":
    "authorization, x-client-info, apikey, content-type",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
};

Deno.serve(async (req: Request) => {
  // Handle browser preflight request
  if (req.method === "OPTIONS") {
    return new Response("ok", {
      headers: corsHeaders,
    });
  }

  try {
    if (req.method !== "POST") {
      return new Response(
        JSON.stringify({
          error: "Method not allowed",
        }),
        {
          status: 405,
          headers: {
            ...corsHeaders,
            "Content-Type": "application/json",
          },
        }
      );
    }

    const body = await req.json();

    const {
      trainee_name,
      trainee_id,
      student_id,
      qualification,
      skill,
      result,
    } = body;

    // =========================
    // VALIDATION
    // =========================

    if (!trainee_name?.trim()) {
      throw new Error("Trainee name is required.");
    }

    if (!student_id?.trim()) {
      throw new Error("Student ID is required.");
    }

    if (!qualification?.trim()) {
      throw new Error("Qualification is required.");
    }

    if (!skill?.trim()) {
      throw new Error("Skill is required.");
    }

    if (!result?.trim()) {
      throw new Error("Result is required.");
    }

    // =========================
    // SUPABASE ADMIN CLIENT
    // =========================

    const supabaseUrl = Deno.env.get("SUPABASE_URL");
    const serviceRoleKey = Deno.env.get(
      "SUPABASE_SERVICE_ROLE_KEY"
    );

    if (!supabaseUrl || !serviceRoleKey) {
      throw new Error(
        "Supabase environment variables are not configured."
      );
    }

    const supabaseAdmin = createClient(
      supabaseUrl,
      serviceRoleKey
    );

    // =========================
    // GENERATE CERTIFICATE ID
    // =========================

    const year = new Date().getFullYear();

    const randomPart = Math.floor(
      100000 + Math.random() * 900000
    );

    const certificateId =
      `CERT-${year}-${randomPart}`;

    // =========================
    // TRAINEE ID
    // =========================

    const traineeId =
      trainee_id?.trim() ||
      `TR-${Date.now()}`;

    // =========================
    // ISSUE DATE
    // =========================

    const issuedOn =
      new Date().toISOString().split("T")[0];

    // =========================
    // INSERT CERTIFICATE
    // =========================

    const { data, error } =
      await supabaseAdmin
        .from("certificates")
        .insert({
          certificate_id: certificateId,

          trainee_id: traineeId,

          trainee_name:
            trainee_name.trim(),

          student_id:
            student_id.trim(),

          qualification:
            qualification.trim(),

          skill:
            skill.trim(),

          issued_on:
            issuedOn,

          result:
            result.trim(),

          // These will be generated by
          // the signing system later.
          token: null,
          hash: null,
          signature: null,

          status: "Valid",
        })
        .select(`
          id,
          certificate_id,
          trainee_id,
          trainee_name,
          student_id,
          qualification,
          skill,
          issued_on,
          result,
          token,
          hash,
          signature,
          status,
          created_at
        `)
        .single();

    if (error) {
      console.error(
        "Certificate insert failed:",
        error
      );

      throw new Error(
        error.message
      );
    }

    // =========================
    // SUCCESS
    // =========================

    return new Response(
      JSON.stringify({
        success: true,
        certificate: data,
      }),
      {
        status: 201,
        headers: {
          ...corsHeaders,
          "Content-Type": "application/json",
        },
      }
    );
  } catch (error) {
    console.error(
      "Create certificate error:",
      error
    );

    return new Response(
      JSON.stringify({
        success: false,
        error:
          error instanceof Error
            ? error.message
            : "Failed to create certificate.",
      }),
      {
        status: 400,
        headers: {
          ...corsHeaders,
          "Content-Type": "application/json",
        },
      }
    );
  }
});